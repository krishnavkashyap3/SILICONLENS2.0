import { useState } from 'react';
import {
  AlertTriangle,
  Check,
  Code2,
  Copy,
  Download,
  ShieldAlert,
  Terminal,
} from 'lucide-react';
import type { ComponentAnalysis, PinCategory } from '../types/analysis';
import { MicrochipSvg } from './MicrochipSvg';
import { StarterCodeCard } from './StarterCodeCard';

interface ResultsDashboardProps {
  analysis: ComponentAnalysis;
}

function getPinTypeBadgeClass(type: PinCategory): string {
  switch (type) {
    case 'Power':
      return 'text-rose-400 font-semibold';
    case 'Ground':
      return 'text-slate-300 font-semibold';
    case 'Input':
      return 'text-sky-400 font-semibold';
    case 'Output':
      return 'text-emerald-400 font-semibold';
    case 'I/O':
      return 'text-violet-400 font-semibold';
    case 'Control':
      return 'text-amber-400 font-semibold';
    default:
      return 'text-slate-500 font-semibold';
  }
}

function buildDatasheetMarkdown(analysis: ComponentAnalysis): string {
  const pinRows = analysis.pinout
    .map(
      (p) =>
        `| ${p.pinNumber} | ${p.pinName} | ${p.type} | ${p.function.replace(/\|/g, '\\|')} |`
    )
    .join('\n');

  const warningsList = analysis.safetyWarnings
    .map(
      (w) =>
        `- **[${w.severity.toUpperCase()}] ${w.title}**: ${w.detail}`
    )
    .join('\n');

  const auditSection =
    analysis.isBreadboardCircuit && analysis.wiringAuditSummary
      ? `\n### Breadboard Wiring Audit\n${analysis.wiringAuditSummary}\n`
      : '';

  return `# ${analysis.componentName} (${analysis.partNumber})

- **Manufacturer:** ${analysis.manufacturer}
- **Package Type:** ${analysis.packageType}
- **Pin Count:** ${analysis.pinCount}
- **Operating Voltage:** ${analysis.operatingVoltage}
- **Pin 1 Orientation:** ${analysis.orientationMarker}

## Overview
${analysis.summary}

## Pinout Specification
| Pin | Name | Type | Function |
| --- | --- | --- | --- |
${pinRows}

## Safety & Wiring Alerts
${auditSection}${warningsList}

## Starter Code (${analysis.starterCode.filename})
\`\`\`cpp
${analysis.starterCode.code}
\`\`\`

---
*Generated by SiliconLens Hardware Lab · Developed by Team DECOY*
`;
}

export function ResultsDashboard({ analysis }: ResultsDashboardProps) {
  const safePinout = Array.isArray(analysis.pinout) ? analysis.pinout : [];
  const safeWarnings = Array.isArray(analysis.safetyWarnings)
    ? analysis.safetyWarnings
    : [];
  const safeStarterCode = analysis.starterCode ?? {
    language: 'Arduino C++',
    filename: 'component_sketch.ino',
    code: '// Starter code was not returned for this component.',
  };

  const normalizedAnalysis: ComponentAnalysis = {
    ...analysis,
    pinout: safePinout,
    safetyWarnings: safeWarnings,
    starterCode: safeStarterCode,
  };

  const [hoveredPinIndex, setHoveredPinIndex] = useState<number | null>(null);
  const [lockedPinIndex, setLockedPinIndex] = useState<number | null>(0);
  const [showRawTelemetry, setShowRawTelemetry] = useState(false);
  const [copiedCodeQuick, setCopiedCodeQuick] = useState(false);
  const [copiedJson, setCopiedJson] = useState(false);

  const activePinIndex = hoveredPinIndex !== null ? hoveredPinIndex : lockedPinIndex;
  const hasCriticalWarning = safeWarnings.some(
    (w) => w.severity === 'critical'
  );
  const rawJsonString = JSON.stringify(normalizedAnalysis, null, 2);

  const handleQuickCopyCode = async () => {
    try {
      await navigator.clipboard.writeText(safeStarterCode.code);
      setCopiedCodeQuick(true);
      setTimeout(() => setCopiedCodeQuick(false), 2000);
    } catch {
      setCopiedCodeQuick(false);
    }
  };

  const handleCopyJson = async () => {
    try {
      await navigator.clipboard.writeText(rawJsonString);
      setCopiedJson(true);
      setTimeout(() => setCopiedJson(false), 2000);
    } catch {
      setCopiedJson(false);
    }
  };

  const handleDownloadMarkdown = () => {
    const markdown = buildDatasheetMarkdown(analysis);
    const blob = new Blob([markdown], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement('a');
    const safeSlug = analysis.partNumber
      .toLowerCase()
      .replace(/[^a-z0-9_-]+/g, '-')
      .replace(/^-|-$/g, '');
    anchor.href = url;
    anchor.download = `${safeSlug || 'component'}-datasheet.md`;
    document.body.appendChild(anchor);
    anchor.click();
    document.body.removeChild(anchor);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-10" aria-label="Component Analysis Results">
      {/* Cyber Telemetry & Quick-Action Toolbar */}
      <div className="cyber-card flex flex-wrap items-center justify-between gap-3 rounded-xl px-5 py-3.5">
        <div className="flex items-center gap-3 font-mono text-xs">
          <span className="text-emerald-400 font-semibold">
            TELEMETRY LOCKED · {analysis.partNumber}
          </span>
          <span className="hidden sm:inline text-slate-600" aria-hidden="true">|</span>
          <span className="hidden sm:inline text-slate-400">
            {analysis.pinout.length} PINS MAPPED
          </span>
        </div>

        <div className="flex flex-wrap items-center gap-2.5">
          <button
            type="button"
            onClick={() => setShowRawTelemetry((prev) => !prev)}
            className={`inline-flex items-center gap-2 rounded-lg border px-3.5 py-1.5 font-mono text-xs font-semibold transition-colors cursor-pointer whitespace-nowrap ${
              showRawTelemetry
                ? 'border-emerald-400 bg-emerald-500/15 text-emerald-300'
                : 'border-cyan-500/40 bg-[#070B14] text-cyan-300 hover:border-cyan-400 hover:bg-cyan-500/10'
            }`}
          >
            <Terminal className="h-3.5 w-3.5" aria-hidden="true" />
            [ &lt;/&gt; Raw Telemetry ]
          </button>

          <button
            type="button"
            onClick={() => void handleQuickCopyCode()}
            className="inline-flex items-center gap-1.5 rounded-lg border border-slate-700 bg-[#070B14] px-3.5 py-1.5 font-mono text-xs font-medium text-slate-200 hover:border-cyan-400/60 hover:text-cyan-200 transition-colors cursor-pointer whitespace-nowrap"
          >
            {copiedCodeQuick ? (
              <>
                <Check className="h-3.5 w-3.5 text-emerald-400" aria-hidden="true" />
                Code Copied
              </>
            ) : (
              <>
                <Copy className="h-3.5 w-3.5 text-cyan-400" aria-hidden="true" />
                Copy Starter Code
              </>
            )}
          </button>

          <button
            type="button"
            onClick={handleDownloadMarkdown}
            className="inline-flex items-center gap-1.5 rounded-lg bg-[#06B6D4] px-3.5 py-1.5 font-mono text-xs font-semibold text-slate-950 hover:bg-cyan-400 transition-colors cursor-pointer whitespace-nowrap"
          >
            <Download className="h-3.5 w-3.5" aria-hidden="true" />
            Download Datasheet Summary (.md)
          </button>
        </div>
      </div>

      {showRawTelemetry ? (
        /* Cyberpunk Raw Telemetry Terminal View */
        <section
          aria-label="Raw Gemini API Telemetry Stream"
          className="cyber-card overflow-hidden rounded-2xl"
        >
          <div className="flex flex-wrap items-center justify-between gap-3 border-b border-emerald-500/25 bg-[#060911] px-5 py-3.5">
            <div className="flex items-center gap-2.5 font-mono text-xs text-emerald-400">
              <Code2 className="h-4 w-4" aria-hidden="true" />
              <span>GEMINI VISION RAW JSON TELEMETRY STREAM</span>
            </div>

            <div className="flex items-center gap-2">
              <button
                type="button"
                onClick={() => void handleCopyJson()}
                className="inline-flex items-center gap-1.5 rounded-lg border border-emerald-500/35 bg-emerald-950/30 px-3 py-1.5 font-mono text-xs font-medium text-emerald-300 hover:bg-emerald-500/15 transition-colors cursor-pointer whitespace-nowrap"
              >
                {copiedJson ? (
                  <>
                    <Check className="h-3.5 w-3.5" aria-hidden="true" />
                    Copied JSON
                  </>
                ) : (
                  <>
                    <Copy className="h-3.5 w-3.5" aria-hidden="true" />
                    Copy JSON
                  </>
                )}
              </button>

              <button
                type="button"
                onClick={() => setShowRawTelemetry(false)}
                className="rounded-lg border border-slate-700 bg-[#0D1526] px-3 py-1.5 font-mono text-xs text-slate-300 hover:text-white transition-colors cursor-pointer whitespace-nowrap"
              >
                Return to Lab HUD
              </button>
            </div>
          </div>

          <div className="code-scroll max-h-[640px] overflow-auto bg-[#04070D] p-5">
            <pre className="font-mono text-xs leading-relaxed text-emerald-300">
              <code>{rawJsonString}</code>
            </pre>
          </div>
        </section>
      ) : (
        <>
          {/* SECTION 1: Component Overview Header Card */}
          <section
            id="overview-section"
            aria-label="Component Overview"
            className="cyber-card scroll-mt-32 rounded-2xl p-6 sm:p-8"
          >
            <div className="flex flex-col gap-6 sm:flex-row sm:items-start sm:justify-between">
              <div className="min-w-0 flex-1">
                <div className="flex flex-wrap items-center gap-x-2.5 gap-y-1 font-mono text-xs text-slate-400">
                  <span className="text-cyan-400 font-semibold">IDENTIFIED PACKAGE</span>
                  <span aria-hidden="true">·</span>
                  <span>{analysis.manufacturer}</span>
                  <span aria-hidden="true">·</span>
                  <span className="text-slate-100 font-semibold">{analysis.partNumber}</span>
                  <span aria-hidden="true">·</span>
                  <span>{analysis.packageType}</span>
                  {analysis.pinCount && (
                    <>
                      <span aria-hidden="true">·</span>
                      <span className="tabular-nums text-emerald-400">
                        {analysis.pinCount}
                      </span>
                    </>
                  )}
                </div>

                <h2 className="mt-2.5 text-2xl font-bold tracking-tight text-white sm:text-3xl text-balance">
                  {analysis.componentName}
                </h2>

                <p className="mt-3 max-w-2xl text-sm leading-relaxed text-slate-300">
                  {analysis.summary}
                </p>

                {analysis.orientationMarker && (
                  <p className="mt-4 font-mono text-xs text-slate-400">
                    <span className="text-cyan-300 font-semibold">PIN-1 MARKER: </span>
                    {analysis.orientationMarker}
                  </p>
                )}
              </div>

              <div className="shrink-0 rounded-xl border border-cyan-500/35 bg-[#070B14] px-5 py-4 sm:min-w-[200px]">
                <span className="block font-mono text-[11px] font-medium text-slate-400">
                  OPERATING VOLTAGE
                </span>
                <span className="mt-1.5 block font-mono text-xl font-bold tabular-nums text-cyan-300">
                  {analysis.operatingVoltage}
                </span>
                <span className="mt-1 block font-mono text-[11px] text-emerald-400">
                  NOMINAL SUPPLY RAIL
                </span>
              </div>
            </div>
          </section>

          {/* SECTION 2: Dedicated Interactive Pinout Inspector */}
          <section
            id="pinout-card"
            aria-label="Interactive Pinout Inspector"
            className="cyber-card scroll-mt-32 rounded-2xl p-6 sm:p-8"
          >
            <div className="mb-6 flex flex-wrap items-center justify-between gap-3 border-b border-cyan-500/20 pb-4">
              <div>
                <span className="font-mono text-[11px] font-semibold tracking-wider text-cyan-400">
                  02. PINOUT &amp; PACKAGE MATRIX
                </span>
                <h3 className="mt-1 text-lg font-semibold text-white">
                  Interactive Microchip &amp; Pinout Inspector
                </h3>
              </div>

              <span className="font-mono text-xs tabular-nums text-emerald-400">
                {analysis.pinout.length} {analysis.pinout.length === 1 ? 'PIN' : 'PINS'} VERIFIED
              </span>
            </div>

            <div className="grid grid-cols-1 gap-8 lg:grid-cols-12 lg:items-start">
              {/* Interactive SVG Chip Graphic */}
              <div className="lg:col-span-5">
                <MicrochipSvg
                  partNumber={analysis.partNumber}
                  packageType={analysis.packageType}
                  operatingVoltage={analysis.operatingVoltage}
                  pinout={analysis.pinout}
                  activePinIndex={activePinIndex}
                  onPinHover={setHoveredPinIndex}
                  onPinClick={(index) =>
                    setLockedPinIndex((prev) => (prev === index ? null : index))
                  }
                />
              </div>

              {/* Synchronized Pinout Table */}
              <div className="overflow-hidden rounded-xl border border-cyan-500/25 bg-[#070B14] lg:col-span-7">
                {analysis.pinout.length > 0 ? (
                  <div className="overflow-x-auto">
                    <table className="w-full border-collapse text-left text-sm">
                      <thead>
                        <tr className="border-b border-cyan-500/25 bg-[#0B1222] font-mono text-xs font-semibold text-cyan-300">
                          <th scope="col" className="px-4 py-3 whitespace-nowrap">
                            Pin
                          </th>
                          <th scope="col" className="px-4 py-3 whitespace-nowrap">
                            Name
                          </th>
                          <th scope="col" className="px-4 py-3 whitespace-nowrap">
                            Type
                          </th>
                          <th scope="col" className="px-4 py-3">
                            Function
                          </th>
                        </tr>
                      </thead>
                      <tbody className="divide-y divide-slate-800/80">
                        {analysis.pinout.map((pin, index) => {
                          const isHighlighted = activePinIndex === index;
                          return (
                            <tr
                              key={`${pin.pinNumber}-${pin.pinName}-${index}`}
                              onMouseEnter={() => setHoveredPinIndex(index)}
                              onMouseLeave={() => setHoveredPinIndex(null)}
                              onClick={() =>
                                setLockedPinIndex((prev) =>
                                  prev === index ? null : index
                                )
                              }
                              className={`cursor-pointer transition-colors ${
                                isHighlighted
                                  ? 'bg-cyan-500/20'
                                  : 'odd:bg-[#070B14] even:bg-[#0A101E] hover:bg-cyan-500/10'
                              }`}
                            >
                              <td className="px-4 py-3 font-mono text-xs font-bold tabular-nums text-cyan-300 whitespace-nowrap">
                                {pin.pinNumber}
                              </td>
                              <td className="px-4 py-3 font-mono text-xs font-semibold text-white whitespace-nowrap">
                                {pin.pinName}
                              </td>
                              <td
                                className={`px-4 py-3 font-mono text-xs whitespace-nowrap ${getPinTypeBadgeClass(
                                  pin.type
                                )}`}
                              >
                                {pin.type}
                              </td>
                              <td className="px-4 py-3 text-xs leading-relaxed text-slate-300">
                                {pin.function}
                              </td>
                            </tr>
                          );
                        })}
                      </tbody>
                    </table>
                  </div>
                ) : (
                  <div className="px-5 py-10 text-center font-mono text-xs text-slate-400">
                    No individual pin definitions were returned for this assembly.
                  </div>
                )}
              </div>
            </div>
          </section>

          {/* SECTION 3: Dedicated Safety & Wiring Audit */}
          <section
            id="safety-card"
            aria-label="Safety and Wiring Alerts"
            className={`scroll-mt-32 rounded-2xl border p-6 sm:p-8 backdrop-blur-md ${
              hasCriticalWarning
                ? 'border-rose-500/40 bg-[#1B0D16]/80'
                : 'border-amber-500/40 bg-[#1A140B]/80'
            }`}
          >
            <div className="mb-6 flex flex-wrap items-center justify-between gap-3 border-b border-amber-500/20 pb-4">
              <div className="flex items-center gap-3">
                {hasCriticalWarning ? (
                  <ShieldAlert
                    className="h-5 w-5 shrink-0 text-rose-400"
                    aria-hidden="true"
                  />
                ) : (
                  <AlertTriangle
                    className="h-5 w-5 shrink-0 text-amber-400"
                    aria-hidden="true"
                  />
                )}
                <div>
                  <span
                    className={`font-mono text-[11px] font-semibold tracking-wider ${
                      hasCriticalWarning ? 'text-rose-400' : 'text-amber-400'
                    }`}
                  >
                    03. ELECTRICAL SAFETY &amp; WIRING AUDIT
                  </span>
                  <h3 className="mt-0.5 text-lg font-semibold text-white">
                    Hardware Protection &amp; Bench Warnings
                  </h3>
                </div>
              </div>

              <span
                className={`font-mono text-xs font-semibold ${
                  hasCriticalWarning ? 'text-rose-300' : 'text-amber-300'
                }`}
              >
                {analysis.safetyWarnings.length} CHECKS LOGGED
              </span>
            </div>

            {analysis.isBreadboardCircuit && analysis.wiringAuditSummary && (
              <div className="mb-5 rounded-xl border border-cyan-500/30 bg-[#080C14]/85 p-4">
                <span className="block font-mono text-xs font-semibold text-cyan-300">
                  BREADBOARD CIRCUIT WIRING AUDIT
                </span>
                <p className="mt-1.5 text-sm leading-relaxed text-slate-200">
                  {analysis.wiringAuditSummary}
                </p>
              </div>
            )}

            <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
              {analysis.safetyWarnings.map((warning, idx) => {
                const isCritical = warning.severity === 'critical';
                return (
                  <div
                    key={`${warning.title}-${idx}`}
                    className={`rounded-xl border p-4 ${
                      isCritical
                        ? 'border-rose-500/35 bg-[#0B0F1A]/90'
                        : 'border-amber-500/35 bg-[#0B0F1A]/90'
                    }`}
                  >
                    <div className="flex items-baseline justify-between gap-2">
                      <h4 className="text-sm font-semibold text-white">
                        {warning.title}
                      </h4>
                      <span
                        className={`font-mono text-[11px] font-semibold shrink-0 ${
                          isCritical ? 'text-rose-400' : 'text-amber-400'
                        }`}
                      >
                        {isCritical ? 'CRITICAL' : 'CAUTION'}
                      </span>
                    </div>
                    <p className="mt-1.5 text-xs leading-relaxed text-slate-300">
                      {warning.detail}
                    </p>
                  </div>
                );
              })}
            </div>
          </section>

          {/* SECTION 4: Dedicated Starter Code & Datasheet Export */}
          <section id="code-card" aria-label="Starter Code and Datasheet Export" className="scroll-mt-32 space-y-4">
            <div className="flex flex-wrap items-end justify-between gap-3 px-1">
              <div>
                <span className="font-mono text-[11px] font-semibold tracking-wider text-cyan-400">
                  04. FIRMWARE &amp; DATASHEET EXPORT
                </span>
                <h3 className="mt-0.5 text-lg font-semibold text-white">
                  Starter Code &amp; Documentation
                </h3>
              </div>

              <button
                type="button"
                onClick={handleDownloadMarkdown}
                className="inline-flex items-center gap-1.5 rounded-lg border border-cyan-500/35 bg-[#0D1526] px-3.5 py-2 font-mono text-xs font-semibold text-cyan-300 hover:border-cyan-400 hover:bg-cyan-500/10 transition-colors cursor-pointer whitespace-nowrap"
              >
                <Download className="h-3.5 w-3.5" aria-hidden="true" />
                Download Datasheet Summary (.md)
              </button>
            </div>

            <StarterCodeCard starterCode={analysis.starterCode} />
          </section>
        </>
      )}
    </div>
  );
}
